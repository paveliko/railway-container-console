#!/usr/bin/env node
/**
 * The rules of `openspec/changes/monorepo-workspace/design.md` §6, as a check
 * that runs in CI.
 *
 * Most of the layering is enforced by things that cannot be argued with: pnpm
 * refuses to resolve a dependency a package did not declare, and an `exports`
 * map refuses a deep import. This script covers only what neither of them can
 * see — a relative path that climbs out of a package, a host string in the
 * wrong place, and a client file reaching for a server package. Each rule below
 * says which criterion it implements, so a failure points at a line in
 * `verification.md` rather than at a regular expression.
 */

import { readFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SEARCH_ROOTS = ['apps', 'packages'];
const SOURCE_EXTENSIONS = ['.ts', '.tsx', '.js', '.jsx', '.mjs', '.cjs', '.graphql'];
const SKIP_DIRECTORIES = new Set(['node_modules', '.next', '.turbo', 'dist', '.git']);
/** Generated by `next build`, git-ignored, and not anybody's source. */
const SKIP_FILES = new Set(['next-env.d.ts']);

/** Every source file under apps/ and packages/, as repo-relative POSIX paths. */
function sourceFiles() {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (SKIP_DIRECTORIES.has(entry)) continue;
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) {
        walk(full);
      } else if (!SKIP_FILES.has(entry) && SOURCE_EXTENSIONS.some((ext) => entry.endsWith(ext))) {
        found.push(relative(ROOT, full).split(sep).join('/'));
      }
    }
  };
  for (const root of SEARCH_ROOTS) walk(join(ROOT, root));
  return found.sort();
}

const files = sourceFiles().map((path) => ({
  path,
  text: readFileSync(join(ROOT, path), 'utf8'),
}));

const problems = [];
const fail = (rule, criterion, detail) => problems.push(`${rule} (${criterion}): ${detail}`);

// ---------------------------------------------------------------------------
// Rule 1 — the host lives in exactly one file, and no socket URL anywhere.
// V-MW-9, restating the parent's V-41.
// ---------------------------------------------------------------------------
{
  const host = 'backboard.railway.com';
  const mentions = files.filter((f) => f.text.includes(host)).map((f) => f.path);
  const allowed = mentions.filter((p) => p.startsWith('packages/railway-client/src/'));

  if (mentions.length !== 1 || allowed.length !== 1) {
    fail(
      'rule 1',
      'V-MW-9',
      `"${host}" must appear in exactly one file under packages/railway-client/src/; ` +
        `found ${mentions.length}: ${mentions.join(', ') || '(none)'}`,
    );
  }
  for (const file of files) {
    if (file.text.includes('wss://')) {
      fail('rule 1', 'V-MW-9', `${file.path} contains a wss:// URL; D-API-7 removed the socket`);
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 2 — GraphQL documents live only in the Railway package.
// V-MW-10, restating the first half of the parent's V-40.
// ---------------------------------------------------------------------------
{
  const RAILWAY = 'packages/railway-client/';
  for (const file of files) {
    if (file.path.endsWith('.graphql') && !file.path.startsWith(RAILWAY)) {
      fail('rule 2', 'V-MW-10', `${file.path} is a GraphQL document outside ${RAILWAY}`);
    }
    if (file.path.startsWith(RAILWAY)) continue;
    // A GraphQL operation in a template literal, not the English word.
    if (/\b(?:query|mutation|subscription)\s+[A-Z]\w*\s*[({]/.test(file.text)) {
      fail('rule 2', 'V-MW-10', `${file.path} appears to contain a GraphQL operation`);
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 3 — no import escapes its own package.
// V-MW-8. pnpm cannot see this one: a relative path never consults package.json.
// ---------------------------------------------------------------------------
{
  const IMPORT = /(?:^|\n)\s*(?:import|export)[\s\S]{0,200}?from\s+['"]([^'"]+)['"]/g;
  // `import 'x'` and `require('x')` carry no `from` clause; a side-effect import
  // crosses a boundary just as loudly as a named one.
  const SIDE_EFFECT = /(?:^|\n)\s*import\s+['"]([^'"]+)['"]/g;
  const DYNAMIC = /\b(?:import|require)\(\s*['"]([^'"]+)['"]\s*\)/g;

  for (const file of files) {
    if (file.path.endsWith('.graphql')) continue;
    const packageRoot = file.path.split('/').slice(0, 2).join('/');
    const specifiers = [
      ...[...file.text.matchAll(IMPORT)].map((m) => m[1]),
      ...[...file.text.matchAll(SIDE_EFFECT)].map((m) => m[1]),
      ...[...file.text.matchAll(DYNAMIC)].map((m) => m[1]),
    ];

    for (const specifier of specifiers) {
      if (specifier.startsWith('.')) {
        const resolved = join(join(ROOT, file.path), '..', specifier);
        const inside = relative(join(ROOT, packageRoot), resolved);
        if (inside.startsWith('..')) {
          fail(
            'rule 3',
            'V-MW-8',
            `${file.path} imports "${specifier}", which leaves ${packageRoot}; ` +
              'cross-package imports go through the package name',
          );
        }
      } else if (/^@repo\/[^/]+\/.+/.test(specifier)) {
        fail(
          'rule 3',
          'V-MW-7',
          `${file.path} deep-imports "${specifier}"; every package exposes "." only`,
        );
      }
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 4 — the server packages stay out of the client import graph.
// V-MW-25, and the static half of the parent's V-15.
// ---------------------------------------------------------------------------
{
  const SERVER_PACKAGES = ['@repo/container-core', '@repo/railway-client'];
  for (const file of files) {
    const isFeature = file.path.startsWith('apps/console/src/features/');
    const isUi = file.path.startsWith('packages/ui/');
    const isClientComponent = /^\s*(['"])use client\1/m.test(file.text);
    if (!isFeature && !isUi && !isClientComponent) continue;

    for (const server of SERVER_PACKAGES) {
      if (new RegExp(`['"]${server}(?:/|['"])`).test(file.text)) {
        fail(
          'rule 4',
          'V-MW-25',
          `${file.path} is in the client graph and imports ${server}; ` +
            'the browser sees @repo/contracts and @repo/ui only',
        );
      }
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 5 — @repo/ui knows nothing about the product.
// V-MW-22. The package.json names itself, so only sources are checked.
// ---------------------------------------------------------------------------
{
  const FORBIDDEN = [
    ['@repo/', 'a workspace import — ui depends on react and nothing else'],
    ['backboard', 'Railway’s host'],
    ['fetch(', 'a network call'],
    ['/api/', 'a route of the console'],
    ['container', 'product vocabulary — a primitive does not know what a container is'],
  ];
  for (const file of files) {
    if (!file.path.startsWith('packages/ui/src/')) continue;
    const haystack = file.text.toLowerCase();
    for (const [needle, why] of FORBIDDEN) {
      if (haystack.includes(needle)) {
        fail('rule 5', 'V-MW-22', `${file.path} contains "${needle}" — ${why}`);
      }
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 6 — ContainerState is declared once, as a schema, in @repo/contracts.
// V-MW-15.
// ---------------------------------------------------------------------------
{
  for (const file of files) {
    if (file.path.startsWith('packages/contracts/src/')) continue;
    if (/\btype\s+ContainerState\s*=\s*\n?\s*\|/.test(file.text)) {
      fail(
        'rule 6',
        'V-MW-15',
        `${file.path} redeclares the ContainerState union; it is inferred from ` +
          'containerStateSchema in @repo/contracts',
      );
    }
  }
}

// ---------------------------------------------------------------------------
// Rule 7 — every @repo/* a package imports is declared in its package.json.
// V-MW-5's backstop. pnpm and tsc between them catch almost all of this, but
// writing the break-and-revert procedure showed one form that escapes both: a
// side-effect `import '@repo/railway-client';` with no bindings raises no
// TS2307, so nothing complains until the module is actually loaded.
// ---------------------------------------------------------------------------
const WORKSPACE_DEPENDENCIES = new Map();
{
  const packageDirs = [];
  for (const root of SEARCH_ROOTS) {
    for (const entry of readdirSync(join(ROOT, root))) {
      const dir = `${root}/${entry}`;
      if (statSync(join(ROOT, dir)).isDirectory()) packageDirs.push(dir);
    }
  }

  const nameOf = new Map();
  for (const dir of packageDirs) {
    const manifest = JSON.parse(readFileSync(join(ROOT, dir, 'package.json'), 'utf8'));
    nameOf.set(dir, manifest.name);
    const declared = new Set([
      ...Object.keys(manifest.dependencies ?? {}),
      ...Object.keys(manifest.devDependencies ?? {}),
      ...Object.keys(manifest.peerDependencies ?? {}),
    ]);
    WORKSPACE_DEPENDENCIES.set(
      manifest.name,
      [...declared].filter((d) => d.startsWith('@repo/')),
    );

    for (const file of files) {
      if (!file.path.startsWith(`${dir}/`)) continue;
      for (const match of file.text.matchAll(/['"](@repo\/[^'"/]+)/g)) {
        const imported = match[1];
        if (imported !== manifest.name && !declared.has(imported)) {
          fail(
            'rule 7',
            'V-MW-5',
            `${file.path} imports ${imported}, which ${manifest.name} does not declare`,
          );
        }
      }
    }
  }

  // ---------------------------------------------------------------------------
  // Rule 8 — the workspace dependency graph is acyclic. D-OPS-2 permits exactly
  // one direction; a cycle would make "which package may know what" unanswerable.
  // ---------------------------------------------------------------------------
  const visiting = new Set();
  const done = new Set();
  const walk = (name, trail) => {
    if (done.has(name)) return;
    if (visiting.has(name)) {
      fail('rule 8', 'V-MW-5', `dependency cycle: ${[...trail, name].join(' → ')}`);
      return;
    }
    visiting.add(name);
    for (const next of WORKSPACE_DEPENDENCIES.get(name) ?? []) {
      walk(next, [...trail, name]);
    }
    visiting.delete(name);
    done.add(name);
  };
  for (const name of WORKSPACE_DEPENDENCIES.keys()) walk(name, []);
}

if (problems.length > 0) {
  console.error(`Boundary check failed — ${problems.length} problem(s):`);
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

console.log(`Boundary check passed: ${files.length} source file(s), 8 rules.`);
